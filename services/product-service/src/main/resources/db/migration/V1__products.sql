CREATE SCHEMA IF NOT EXISTS product_service;
CREATE TABLE IF NOT EXISTS product_service.categories (id BIGSERIAL PRIMARY KEY, name VARCHAR(255) NOT NULL UNIQUE, description VARCHAR(500));
CREATE TABLE IF NOT EXISTS product_service.products (id BIGSERIAL PRIMARY KEY, sku VARCHAR(100) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL, price NUMERIC(12,2) NOT NULL, category VARCHAR(255));
